        assertContentEquals(
            out1,
            ClearAdiProvision.decryptPtm(
                hex("8381bbd8003f9ed7390393bf7eeda953"),
                hex("f0cf811a69d9409aeebf10408f6cb041"),
                hex("5d1e485cd273e35ca37c8ec0a0ebb62f"),
            ),
        )
        val out2 = hex(
            "e482e99a56404b6f4c0157a9b50f0753" +
                "e4aa04c6fde42ee55e4565d63075de0b",
        )
        assertContentEquals(
            out2,
            ClearAdiProvision.decryptPtm(
                hex("c5917a6a1a47f8714b627cc428e4ea9f"),
                hex("32e040ac83e19a34001ffa443963f18d" +
